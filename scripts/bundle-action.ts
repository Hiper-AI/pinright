/**
 * Builds the GitHub Action bundle: src/action/main.ts and everything it imports
 * (undici, semver, zod) in one ESM file, committed at action-dist/index.mjs so
 * the action runs from its checkout with no install step. Deterministic: no
 * timestamps, no absolute paths; CI rebuilds it and fails if it differs.
 * Run: npm run bundle:action
 */
import { build } from 'esbuild';

const result = await build({
  entryPoints: ['src/action/main.ts'],
  outfile: 'action-dist/index.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  minify: false,
  legalComments: 'eof',
  sourcemap: false,
  metafile: true,
  // CommonJS dependencies (semver, undici) call require() for Node builtins; ESM output needs one.
  banner: {
    js: [
      '// pinright GitHub Action bundle. Generated by scripts/bundle-action.ts from src/action/main.ts; do not edit.',
      "import { createRequire as __pinrightCreateRequire } from 'node:module';",
      'const require = __pinrightCreateRequire(import.meta.url);',
    ].join('\n'),
  },
  logLevel: 'warning',
});

const bytes = Object.values(result.metafile.outputs).reduce((n, o) => n + o.bytes, 0);
console.log(`action-dist/index.mjs: ${(bytes / 1024).toFixed(0)} KiB`);
